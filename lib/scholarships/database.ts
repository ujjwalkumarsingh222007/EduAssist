export async function searchDatabaseScholarships(): Promise<Scholarship[]> {
  try {
    const supabase = await createClient();
    const { data, error } = await supabase
      .from("scholarships")
      .select("*")
      .order("deadline", { ascending: true });

    if (error || !data || data.length === 0) {
      // Return curated verified database catalog
      return CURATED_SCHOLARSHIPS_CATALOG;
    }

    return data.map((row) => ({
      id: row.id,
      title: row.title,
      provider: row.provider,
      description: row.description || "",
      amount: row.amount,
      deadline: row.deadline || "2026-12-31",
      education_levels: row.education_levels || ["Undergraduate"],
      courses: row.courses || ["All"],
      minimum_percentage: row.minimum_percentage ? Number(row.minimum_percentage) : null,
      maximum_income: row.maximum_income ? Number(row.maximum_income) : null,
      eligible_gender: row.eligible_gender || "Any",
      eligible_categories: row.eligible_categories || ["All"],
      eligible_states: row.eligible_states || ["All India"],
      required_documents: row.required_documents || ["Marksheet", "Aadhaar Card"],
      application_url: row.application_url,
      source_url: row.source_url,
      source_name: row.source_name,
      source_type: "database",
      date_found: row.created_at ? row.created_at.split("T")[0] : new Date().toISOString().split("T")[0],
      is_verified: row.is_verified ?? true,
    }));
  } catch (err) {
    console.error("Database scholarship search error:", err);
    return CURATED_SCHOLARSHIPS_CATALOG;
  }
}
